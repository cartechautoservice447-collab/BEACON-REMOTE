using System.Text.Json.Serialization;
using Beacon.Companion.Core.Credentials;

namespace Beacon.Companion.Core.Pairing;

/// <summary>
/// Device metadata sent inside <c>POST /api/public/agent/pair</c>.
/// Matches <c>deviceSchema</c> in <c>src/routes/api/public/agent/pair.ts</c> and PostgreSQL <c>public.devices</c> constraints.
/// </summary>
public sealed record PairingDeviceMetadata(
    [property: JsonPropertyName("name")] string Name,
    [property: JsonPropertyName("os")] string Os,
    [property: JsonPropertyName("agent_version")] string AgentVersion)
{
    public PairingDeviceMetadata NormalizeAndValidate()
    {
        var name = Name?.Trim() ?? string.Empty;
        var os = Os?.Trim() ?? string.Empty;
        var version = AgentVersion?.Trim() ?? string.Empty;

        if (name.Length is < 1 or > 64)
        {
            throw new ArgumentException("Device name must be 1..64 non-whitespace characters.", nameof(Name));
        }

        if (os.Length is < 1 or > 64)
        {
            throw new ArgumentException("Device OS description must be 1..64 non-whitespace characters.", nameof(Os));
        }

        if (version.Length is < 1 or > 32)
        {
            throw new ArgumentException("Agent version must be 1..32 non-whitespace characters.", nameof(AgentVersion));
        }

        return new PairingDeviceMetadata(name, os, version);
    }

    public bool TryNormalize(out PairingDeviceMetadata? normalized, out string? errorDetail)
    {
        var name = Name?.Trim() ?? string.Empty;
        var os = Os?.Trim() ?? string.Empty;
        var version = AgentVersion?.Trim() ?? string.Empty;

        if (name.Length is < 1 or > 64)
        {
            normalized = null;
            errorDetail = "Device name must be 1..64 non-whitespace characters.";
            return false;
        }

        if (os.Length is < 1 or > 64)
        {
            normalized = null;
            errorDetail = "Device OS description must be 1..64 non-whitespace characters.";
            return false;
        }

        if (version.Length is < 1 or > 32)
        {
            normalized = null;
            errorDetail = "Agent version must be 1..32 non-whitespace characters.";
            return false;
        }

        normalized = new PairingDeviceMetadata(name, os, version);
        errorDetail = null;
        return true;
    }
}

