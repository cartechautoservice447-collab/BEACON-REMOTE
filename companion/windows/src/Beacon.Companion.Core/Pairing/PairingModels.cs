public enum PairingFailureReason
{
    None = 0,
    InvalidPinFormat = 1,
    InvalidQrPayload = 2,
    UnsupportedQrVersion = 3,
    UntrustedServerOrigin = 4,
    InsecureServerOrigin = 5,
    InvalidDeviceMetadata = 6,
    AlreadyPaired = 7,
    ClientRateLimited = 8,
    CredentialStoreUnavailablePreFlight = 9,
    InvalidOrLockedCodeOrToken = 10,
    PairingSessionExpired = 11,
    ServerRateLimited = 12,
    BadRequestRejectedByServer = 13,
    ServerError = 14,
    UnexpectedRedirect = 15,
    MalformedServerResponse = 16,
    NetworkErrorBeforeRequestSent = 17,
    AmbiguousServerOutcomeAfterRequestSent = 18,
    Cancelled = 19,
    CredentialPersistenceFailedAfterServerConfirm = 20,
