public sealed record PairingAttemptResult(
    bool Succeeded,
    DeviceCredentialMetadata? CredentialMetadata = null,
    PairingFailureReason FailureReason = PairingFailureReason.None,
    int? HttpStatusCode = null,
    string? ServerErrorCode = null,
    Guid? OrphanedDeviceId = null,
    bool IsOutcomeAmbiguous = false,
    string? UserGuidance = null)
{
    public static PairingAttemptResult Success(DeviceCredentialMetadata metadata)
    {
        ArgumentNullException.ThrowIfNull(metadata);
        return new(true, metadata);
    }

    public static PairingAttemptResult Failure(
        PairingFailureReason reason,
        string userGuidance,
        int? httpStatusCode = null,
        string? serverErrorCode = null,
        Guid? orphanedDeviceId = null,
        bool isOutcomeAmbiguous = false) =>
        new(
            Succeeded: false,
            CredentialMetadata: null,
            FailureReason: reason,
            HttpStatusCode: httpStatusCode,
            ServerErrorCode: serverErrorCode,
            OrphanedDeviceId: orphanedDeviceId,
            IsOutcomeAmbiguous: isOutcomeAmbiguous,
            UserGuidance: userGuidance);
}
